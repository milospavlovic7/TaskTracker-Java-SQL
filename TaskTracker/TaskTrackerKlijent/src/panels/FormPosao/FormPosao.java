    private void jButtonObrisiPosaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonObrisiPosaoActionPerformed
        int result = JOptionPane.showConfirmDialog(this, "Da li ste sigurni da želite da obrišete ovaj posao?", 
                                                 "Konfirmacija", JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.NO_OPTION) {
            return;
        }

        if (selektovaniPosao == null) {
            JOptionPane.showMessageDialog(this, "Nije selektovan posao!");
            return;
        }

        // Prvo brisanje svih pripadnosti zadacima
        try {
            ArrayList<PripadnostZadatkaPoslu> svePripadnosti = ClientController.getInstance().getAllPripadnostiZP();
            for (PripadnostZadatkaPoslu prip : svePripadnosti) {
                if (prip.getPosaoID().equals(selektovaniPosao.getPosaoID())) {
                    ClientController.getInstance().deletePripadnostZP(prip);
                }
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri brisanju pripadnosti zadacima: " + ex.getMessage());
            return; // Prekidamo izvršavanje ukoliko nastane greška
        }

        // Nakon toga brisanje svih zaposlenja vezanih za taj posao
        try {
            ArrayList<Zaposlenje> svaZaposljenja = ClientController.getInstance().getAllZaposlenja();
            for (Zaposlenje z : svaZaposljenja) {
                if (z.getPosaoID().equals(selektovaniPosao.getPosaoID())) {
                    ClientController.getInstance().deleteZaposlenje(z);
                }
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri brisanju zaposlenja: " + ex.getMessage());
            return;
        }

        // Na kraju, brisanje samog posla
        try {
            ClientController.getInstance().deletePosao(selektovaniPosao);
            JOptionPane.showMessageDialog(this, "Posao i sve povezane veze su uspešno obrisani.");
            popuniComboBoxPoslovi();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška prilikom brisanja posla: " + ex.getMessage());
        }

        setLastPosao();
    }//GEN-LAST:event_jButtonObrisiPosaoActionPerformed

    private void jButtonIzmeniPosaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonIzmeniPosaoActionPerformed
        // Ako trenutno nije u režimu izmene (tekst je "Izmeni Posao")
        if(jButtonIzmeniPosao.getText().equals("Izmeni Posao")){
            // Omogućavamo uređivanje
            jTextFieldNazivPosla.setEditable(true);
            jTextAreaOpisPosla.setEditable(true);
            // Menjamo tekst na dugmetu
            jButtonIzmeniPosao.setText("Sacuvaj");
            // Prikazujemo dugme za odustajanje
            jButtonOdustaniOdIzmene.setVisible(true);
        } else {
            // U režimu smo "Sacuvaj", dakle pokupimo izmene
            String noviNaziv = jTextFieldNazivPosla.getText().trim();
            String noviOpis = jTextAreaOpisPosla.getText().trim();
            
            // Možete dodati validaciju (npr. ne smeju biti prazni)
            if(noviNaziv.isEmpty() || noviOpis.isEmpty()){
                JOptionPane.showMessageDialog(this, "Naziv i opis ne mogu biti prazni!");
                return;
            }
            
            // Preuzmemo trenutni posao iz combo box-a
            if(selektovaniPosao == null){
                JOptionPane.showMessageDialog(this, "Nije selektovan posao!");
                return;
            }
            
            try {
                poslovi = ClientController.getInstance().getAllPoslovi();
                for(Posao p : poslovi){
                    if(noviNaziv.equals(p.getNazivPosla()) && !noviNaziv.equals(selektovaniPosao.getNazivPosla())){
                        JOptionPane.showMessageDialog(this, "Posao sa ovim nazivom vec postoji!");
                        return;
                    }
                }
            } catch (Exception ex) {
                Logger.getLogger(FormNoviPosao.class.getName()).log(Level.SEVERE, null, ex);
            }
            
            // Postavljamo nove vrednosti
            selektovaniPosao.setNazivPosla(noviNaziv);
            selektovaniPosao.setOpisPosla(noviOpis);
            
            try {
                ClientController.getInstance().updatePosao(selektovaniPosao);
                JOptionPane.showMessageDialog(this, "Posao je uspešno izmenjen!");
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Greška prilikom izmene posla: " + ex.getMessage());
                Logger.getLogger(FormPosao.class.getName()).log(Level.SEVERE, null, ex);
            }
            
            // Vraćamo polja u režim neizmenjivosti
            jTextFieldNazivPosla.setEditable(false);
            jTextAreaOpisPosla.setEditable(false);
            // Vraćamo tekst dugmeta na početni
            jButtonIzmeniPosao.setText("Izmeni Posao");
            // Sakrivamo dugme odustani
            jButtonOdustaniOdIzmene.setVisible(false);
            
            // Ažuriramo prikaz (možete osvežiti combo box ili samo prikaz podataka)
            popuniComboBoxPoslovi();
            refreshAll();
        }
    }//GEN-LAST:event_jButtonIzmeniPosaoActionPerformed

