    private void popuniTabeleZaposleni(){
        try {
            if(selektovaniPosao == null) {
                return;
            }

            // Učitaj sve zaposlene i zaposlenja
            ArrayList<Zaposleni> sviZaposleni = ClientController.getInstance().getAllZaposleni();
            // Pretpostavljamo da metoda getAllZaposlenje() vraća ArrayList<domain.Zaposlenje>
            ArrayList<Zaposlenje> svaZaposljenja = ClientController.getInstance().getAllZaposlenja();

            // Filtriraj zaposlenja koja se odnose na selektovani posla
            ArrayList<Zaposleni> zaposleniNaPoslu = new ArrayList<>();
            for(domain.Zaposlenje z : svaZaposljenja) {
                // Pretpostavljamo da Posao ima metodu getPosaoID() – prilagodi prema tvojoj implementaciji
                if(z.getPosaoID().equals(selektovaniPosao.getPosaoID())){
                    // Na osnovu ID-ja zaposlenog, pronađi odgovarajućeg zaposlenog
                    for(Zaposleni zap : sviZaposleni) {
                        if(zap.getZaposleniID().equals(z.getZaposleniID())){
                            zaposleniNaPoslu.add(zap);
                            break;
                        }
                    }
                }
            }

            // Kreiraj listu zaposlenih koji nisu na poslu: sviZaposleni - zaposleniNaPoslu
            ArrayList<Zaposleni> zaposleniVanPosla = new ArrayList<>(sviZaposleni);
            // Ako equals nije pravilno implementiran, možeš koristiti ručno uklanjanje:
            for(Zaposleni zapNaPoslu : zaposleniNaPoslu) {
                for (int i = 0; i < zaposleniVanPosla.size(); i++) {
                    Zaposleni zapVan = zaposleniVanPosla.get(i);
                    if(zapVan.getZaposleniID().equals(zapNaPoslu.getZaposleniID())){
                        zaposleniVanPosla.remove(i);
                        break;
                    }
                }
            }

            // Postavi modele tabela koristeći novi konstruktor
            TableModelZaposleni modelNaPoslu = new TableModelZaposleni(zaposleniNaPoslu);
            TableModelZaposleni modelVanPosla = new TableModelZaposleni(zaposleniVanPosla);
            jTableZaposleniNaPoslu.setModel(modelNaPoslu);
            jTableZaposleniVanPosla.setModel(modelVanPosla);
            
            
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri učitavanju zaposlenih: " + ex.getMessage());
        }
    }
  
    private void popuniTabeleZadaci() {
        try {
            if (selektovaniPosao == null) {
                return;
            }

            // Učitavanje svih zadataka i pripadnosti
            ArrayList<Zadatak> sviZadaci = ClientController.getInstance().getAllZadaci();
            ArrayList<PripadnostZadatkaPoslu> svePripadnosti = ClientController.getInstance().getAllPripadnostiZP();

            // Filter zadataka koji su vezani za izabrani posao
            ArrayList<Zadatak> zadaciNaPoslu = new ArrayList<>();
            for (PripadnostZadatkaPoslu p : svePripadnosti) {
                if (p.getPosaoID().equals(selektovaniPosao.getPosaoID())) {
                    for (Zadatak z : sviZadaci) {
                        if (z.getZadatakID().equals(p.getZadatakID())) {
                            zadaciNaPoslu.add(z);
                            break;
                        }
                    }
                }
            }

            // Zadaci koji nisu dodeljeni tom poslu
            ArrayList<Zadatak> zadaciVanPosla = new ArrayList<>(sviZadaci);
            for (Zadatak z : zadaciNaPoslu) {
                zadaciVanPosla.removeIf(zv -> zv.getZadatakID().equals(z.getZadatakID()));
            }

            // Postavljanje modela tabela
            TableModelZadaci modelNaPoslu = new TableModelZadaci(zadaciNaPoslu);
            TableModelZadaci modelVanPosla = new TableModelZadaci(zadaciVanPosla);
            jTableZadaciNaPoslu.setModel(modelNaPoslu);
            jTableZadaciVanPosla.setModel(modelVanPosla);

            
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri učitavanju zadataka: " + ex.getMessage());
        }
    }
    
