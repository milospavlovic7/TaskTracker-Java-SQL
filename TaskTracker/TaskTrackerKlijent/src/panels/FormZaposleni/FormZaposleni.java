    private void jButtonIzmeniZaposlenogActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonIzmeniZaposlenogActionPerformed
        // Ako trenutno nismo u režimu izmene
        if(jButtonIzmeniZaposlenog.getText().equals("Izmeni zaposlenog")){
            omoguciIzmenu(true);
            jButtonIzmeniZaposlenog.setText("Sačuvaj");
            jButtonOdustaniOdIzmene.setVisible(true);
        } else {
            // U režimu "Sačuvaj", pokupimo izmene
            String ime = jTextFieldImeZaposlenog.getText().trim();
            String prezime = jTextFieldPrezimeZaposlenog.getText().trim();
            String telefon = jTextFieldTelefonZaposlenog.getText().trim();
            String email = jTextFieldEmailZaposlenog.getText().trim();
            String lozinka = new String(jPasswordLozinkaZaposlenog.getPassword()).trim();

            // Validacija unosa – sva polja moraju biti popunjena
            if(ime.isEmpty() || prezime.isEmpty() || telefon.isEmpty() || email.isEmpty() || lozinka.isEmpty()){
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
                return;
            }
            
            // Preuzimanje selektovanog zaposlenog
            if(selektovaniZaposleni == null){
                JOptionPane.showMessageDialog(this, "Nije selektovan zaposleni!");
                return;
            }
            
            // Provera jedinstvenosti email-a
            try {
                zaposleni = ClientController.getInstance().getAllZaposleni();
                for(Zaposleni z : zaposleni){
                    if(email.equals(z.getEmail()) && !email.equals(selektovaniZaposleni.getEmail())){
                        JOptionPane.showMessageDialog(this, "Zaposleni sa ovim email-om već postoji!");
                        return;
                    }
                }
            } catch (Exception ex) {
                Logger.getLogger(FormZaposleni.class.getName()).log(Level.SEVERE, null, ex);
            }
            
            // Postavljanje novih vrednosti
            selektovaniZaposleni.setIme(ime);
            selektovaniZaposleni.setPrezime(prezime);
            selektovaniZaposleni.setTelefon(telefon);
            selektovaniZaposleni.setEmail(email);
            selektovaniZaposleni.setLozinka(lozinka);
            
            // Pokušaj slanja izmenjenog zaposlenog serveru
            try {
                ClientController.getInstance().updateZaposleni(selektovaniZaposleni);
                JOptionPane.showMessageDialog(this, "Zaposleni je uspešno izmenjen!");
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Greška prilikom izmene zaposlenog: " + ex.getMessage());
                Logger.getLogger(FormZaposleni.class.getName()).log(Level.SEVERE, null, ex);
            }
            
            // Vraćamo formu u režim pregleda
            omoguciIzmenu(false);
            jButtonIzmeniZaposlenog.setText("Izmeni zaposlenog");
            jButtonOdustaniOdIzmene.setVisible(false);
            popuniComboBoxZaposleni();
            refreshAll();
        }
    }//GEN-LAST:event_jButtonIzmeniZaposlenogActionPerformed

