    public void setLastZaposleni() {
        if (zaposleni != null && !zaposleni.isEmpty()) {
            Zaposleni poslednji = zaposleni.get(zaposleni.size() - 1);
            setSelectedZaposleni(poslednji);
            refreshAll();
        }
    }
    
    private void refreshAll() {
        java.awt.Window win = javax.swing.SwingUtilities.getWindowAncestor(this);
        if (win instanceof forms.MainFormMenadzer) {
            forms.MainFormMenadzer mainForm = (forms.MainFormMenadzer) win;
            mainForm.refreshAllMain();
        } else {
            System.out.println("Nije pronađena instanca MainFormMenadzer!");
        }
    }

