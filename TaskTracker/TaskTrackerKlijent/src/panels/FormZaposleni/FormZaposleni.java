    private void jButtonObrisiZaposlenogActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonObrisiZaposlenogActionPerformed
        int result = JOptionPane.showConfirmDialog(this, "Da li ste sigurni da želite da obrišete ovog zaposlenog?", 
                                                    "Konfirmacija", JOptionPane.YES_NO_OPTION);

        if(result == JOptionPane.NO_OPTION){
            return;
        }
        
        if(selektovaniZaposleni == null) {
            JOptionPane.showMessageDialog(this, "Nije selektovan zaposleni!");
            return;
        }
        
        // Brisanje svih zaposlenja vezanih za taj posao
        try {
            ArrayList<Zaposlenje> svaZaposljenja = ClientController.getInstance().getAllZaposlenja();
            for (Zaposlenje z : svaZaposljenja) {
                if (z.getZaposleniID().equals(selektovaniZaposleni.getZaposleniID())) {
                    ClientController.getInstance().deleteZaposlenje(z);
                }
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri brisanju zaposlenja: " + ex.getMessage());
            return;
        }
        
        try {
            ClientController.getInstance().deleteZaposleni(selektovaniZaposleni);
            popuniComboBoxZaposleni();
            JOptionPane.showMessageDialog(this, "Zaposleni je uspešno obrisan!");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška prilikom brisanja zaposlenog: " + ex.getMessage());
            Logger.getLogger(FormZaposleni.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        setLastZaposleni();
    }//GEN-LAST:event_jButtonObrisiZaposlenogActionPerformed

    private void jButtonUkloniPosaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUkloniPosaoActionPerformed
        if (selektovaniZaposleni == null) {
            JOptionPane.showMessageDialog(this, "Nije selektovan zaposleni!");
            return;
        }

        int red = jTablePosloviPovezani.getSelectedRow();
        if (red < 0) {
            JOptionPane.showMessageDialog(this, "Nije selektovan posao za uklanjanje.");
            return;
        }

        TableModelPoslovi modelPoslovi = (TableModelPoslovi) jTablePosloviPovezani.getModel();
        Posao selektovaniPosao = modelPoslovi.getSelectedPosao(red);

        try {
            ArrayList<Zaposlenje> svaZaposlenja = ClientController.getInstance().getAllZaposlenja();
            Zaposlenje zaposleniZaBrisanje = null;

            for (Zaposlenje z : svaZaposlenja) {
                if (z.getZaposleniID().equals(selektovaniZaposleni.getZaposleniID()) &&
                    z.getPosaoID().equals(selektovaniPosao.getPosaoID())) {
                    zaposleniZaBrisanje = z;
                    break;
                }
            }

            if (zaposleniZaBrisanje != null) {
                ClientController.getInstance().deleteZaposlenje(zaposleniZaBrisanje);
                JOptionPane.showMessageDialog(this, "Zaposleni je uklonjen sa posla.");
                popuniTabelePoslovi(); // osvežava tabele poslova vezanih/van zadatka
                popuniTabeluZadaci();
                refreshAll();
            } else {
                JOptionPane.showMessageDialog(this, "Nije pronađeno zaposlenje za uklanjanje.");
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri uklanjanju zaposlenog sa posla: " + ex.getMessage());
        }

    }//GEN-LAST:event_jButtonUkloniPosaoActionPerformed

    private void jButtonDodajPosaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDodajPosaoActionPerformed
        if (selektovaniZaposleni == null) {
            JOptionPane.showMessageDialog(this, "Nije selektovan zaposleni!");
            return;
        }

        int red = jTablePosloviNepovezani.getSelectedRow();
        if (red < 0) {
            JOptionPane.showMessageDialog(this, "Nije selektovan posao za dodavanje.");
            return;
        }

        TableModelPoslovi modelBezZadatka = (TableModelPoslovi) jTablePosloviNepovezani.getModel();
        Posao selektovaniPosao = modelBezZadatka.getSelectedPosao(red);

        try {
            // Provera da li zaposleni već ima dodeljen posao
            ArrayList<Zaposlenje> svaZaposlenja = ClientController.getInstance().getAllZaposlenja();
            for (Zaposlenje z : svaZaposlenja) {
                if (z.getZaposleniID().equals(selektovaniZaposleni.getZaposleniID()) &&
                    z.getPosaoID().equals(selektovaniPosao.getPosaoID())) {
                    JOptionPane.showMessageDialog(this, "Zaposleni je već povezan sa ovim poslom.");
                    return;
                }
            }

            // Kreiranje novog zaposlenja: postavljamo datum početka na trenutni, datum završetka može biti null
            Zaposlenje novoZaposlenje = new Zaposlenje();
            novoZaposlenje.setZaposleniID(selektovaniZaposleni.getZaposleniID());
            novoZaposlenje.setPosaoID(selektovaniPosao.getPosaoID());
            novoZaposlenje.setDatumPocetkaZap(new java.util.Date());
            novoZaposlenje.setDatumZavrsetkaZap(null);

            ClientController.getInstance().addZaposlenje(novoZaposlenje);
            JOptionPane.showMessageDialog(this, "Zaposleni je dodat na posao.");
            popuniTabelePoslovi();
            popuniTabeluZadaci();
            refreshAll();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri dodavanju zaposlenog na posao: " + ex.getMessage());
        }

    }//GEN-LAST:event_jButtonDodajPosaoActionPerformed

