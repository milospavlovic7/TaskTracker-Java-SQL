    private void otvoriFormuZaposleni(Zaposleni zap) {
        // Dobavi roditeljsku formu (MainFormMenadzer) preko SwingUtilities, a zatim pozovi setter na formi Zaposleni:
        java.awt.Window win = javax.swing.SwingUtilities.getWindowAncestor(this);
        if(win instanceof forms.MainFormMenadzer) {
            forms.MainFormMenadzer mainForm = (forms.MainFormMenadzer) win;
            // Postavi selektovanog zaposlenog u FormZaposleni i prebaci karticu na Zaposleni panel
            mainForm.getFormZaposleni().setSelectedZaposleni(zap);
            mainForm.navigateToPanel("Zaposleni");
        } else {
            System.out.println("Nije pronađena instanca MainFormMenadzer!");
        }
    }
    
