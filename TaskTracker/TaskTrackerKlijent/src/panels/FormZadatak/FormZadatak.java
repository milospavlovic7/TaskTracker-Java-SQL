    private void jButtonObrisiZadatakActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonObrisiZadatakActionPerformed
        int result = JOptionPane.showConfirmDialog(this, 
                "Da li ste sigurni da zelite da obrisete ovaj zadatak?", 
                "Konfirmacija", 
                JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.NO_OPTION) {
            return;
        }
        
        if (selektovaniZadatak == null) {
            JOptionPane.showMessageDialog(this, "Nije selektovan zadatak!");
            return;
        }
        
        // Prvo brisanje svih pripadnosti poslovima
        try {
            ArrayList<PripadnostZadatkaPoslu> svePripadnosti = ClientController.getInstance().getAllPripadnostiZP();
            for (PripadnostZadatkaPoslu prip : svePripadnosti) {
                if (prip.getZadatakID().equals(selektovaniZadatak.getZadatakID())) {
                    ClientController.getInstance().deletePripadnostZP(prip);
                }
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri brisanju pripadnosti zadacima: " + ex.getMessage());
            return; // Prekidamo izvršavanje ukoliko nastane greška
        }

        if (result == JOptionPane.YES_OPTION) {
            try {
                Zadatak zadatakZaBrisanje = (Zadatak) jComboBoxListaZadataka.getSelectedItem();
                ClientController.getInstance().deleteZadatak(zadatakZaBrisanje);
                popuniComboBoxZadaci();
                JOptionPane.showMessageDialog(this, "Uspesno obrisan zadatak.");
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Ne mozete da obrisete ovaj zadatak: " + ex.getMessage());
            }
        }
        
        setLastZadatak();
    }//GEN-LAST:event_jButtonObrisiZadatakActionPerformed

    private void jButtonIzmeniZadatakActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonIzmeniZadatakActionPerformed
        // Ako trenutno nije u režimu izmene (tekst je "Izmeni Zadatak")
        if (jButtonIzmeniZadatak.getText().equals("Izmeni Zadatak")) {
            omoguciIzmenu(true);
            jButtonIzmeniZadatak.setText("Sacuvaj");
            jButtonOdustaniOdIzmene.setVisible(true);
        } else {
            // U režimu "Sacuvaj", pokupimo izmene
            String noviNaziv = jTextFieldNazivZadatka.getText().trim();
            String noviOpis = jTextAreaOpisZadatka.getText().trim();

            if (noviNaziv.isEmpty() || noviOpis.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Naziv i opis ne mogu biti prazni!");
                return;
            }

            if (selektovaniZadatak == null) {
                JOptionPane.showMessageDialog(this, "Nije selektovan zadatak!");
                return;
            }

            try {
                ArrayList<Zadatak> sviZadaci = ClientController.getInstance().getAllZadaci();
                for (Zadatak z : sviZadaci) {
                    // Provera da ne postoji drugi zadatak sa istim nazivom
                    if (noviNaziv.equals(z.getNazivZadatka()) && !noviNaziv.equals(selektovaniZadatak.getNazivZadatka())) {
                        JOptionPane.showMessageDialog(this, "Zadatak sa ovim nazivom već postoji!");
                        return;
                    }
                }
            } catch (Exception ex) {
                Logger.getLogger(FormNoviZadatak.class.getName()).log(Level.SEVERE, null, ex);
            }

            // Postavljanje novih vrednosti
            selektovaniZadatak.setNazivZadatka(noviNaziv);
            selektovaniZadatak.setOpisZadatka(noviOpis);
            // Preuzimamo izabran status iz combo boxa
            StatusZadatka noviStatus = (StatusZadatka) jComboBoxStatusZadatka.getSelectedItem();
            selektovaniZadatak.setStatusZadatka(noviStatus);

            try {
                ClientController.getInstance().updateZadatak(selektovaniZadatak);
                JOptionPane.showMessageDialog(this, "Zadatak je uspešno izmenjen!");
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Greška prilikom izmene zadatka: " + ex.getMessage());
                Logger.getLogger(FormZadatak.class.getName()).log(Level.SEVERE, null, ex);
            }

            omoguciIzmenu(false);
            jButtonIzmeniZadatak.setText("Izmeni Zadatak");
            jButtonOdustaniOdIzmene.setVisible(false);
            popuniComboBoxZadaci();
            refreshAll();
        }
    }//GEN-LAST:event_jButtonIzmeniZadatakActionPerformed

