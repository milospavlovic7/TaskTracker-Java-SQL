    private void popuniTabeluZaposleni() {
        try {
            if (selektovaniZadatak == null) {
                return;
            }

            // 1. Učitaj sve pripadnosti zadatka-poslu
            ArrayList<PripadnostZadatkaPoslu> svePripadnosti = ClientController.getInstance().getAllPripadnostiZP();
            // Filtriraj pripadnosti gde je ZadatakID jednak ID-ju selektovanog zadatka
            ArrayList<Long> povezaniPosloviIds = new ArrayList<>();
            for (PripadnostZadatkaPoslu p : svePripadnosti) {
                if (p.getZadatakID().equals(selektovaniZadatak.getZadatakID())) {
                    // Dodaj PosaoID samo ako nije već dodat (bez dupliranja)
                    if (!povezaniPosloviIds.contains(p.getPosaoID())) {
                        povezaniPosloviIds.add(p.getPosaoID());
                    }
                }
            }

            // 2. Učitaj sva zaposlenja (angl. "employments")
            ArrayList<Zaposlenje> svaZaposljenja = ClientController.getInstance().getAllZaposlenja();
            // Iz zaposlenja izdvoji jedinstvene ZaposleniID-je koji su povezani sa poslovima iz povezaniPosloviIds
            ArrayList<Long> zaposleniIds = new ArrayList<>();
            for (Zaposlenje z : svaZaposljenja) {
                if (povezaniPosloviIds.contains(z.getPosaoID())) {
                    if (!zaposleniIds.contains(z.getZaposleniID())) {
                        zaposleniIds.add(z.getZaposleniID());
                    }
                }
            }

            // 3. Učitaj sve zaposlene
            ArrayList<Zaposleni> sviZaposleni = ClientController.getInstance().getAllZaposleni();
            // Filtriraj samo one zaposlene čiji ID se nalazi u listi zaposleniIds
            ArrayList<Zaposleni> zaposleniZaZadatak = new ArrayList<>();
            for (Zaposleni zap : sviZaposleni) {
                if (zaposleniIds.contains(zap.getZaposleniID())) {
                    zaposleniZaZadatak.add(zap);
                }
            }

            // 4. Postavi model tabele (bez duplikata)
            jTableZaposleniZadatka.setModel(new models.TableModelZaposleni(zaposleniZaZadatak));

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri učitavanju zaposlenih: " + ex.getMessage());
        }
    }
 
    private void popuniTabelePoslovi() {
        try {
            if (selektovaniZadatak == null) {
                return;
            }

            // Učitavanje svih poslova i pripadnosti
            ArrayList<Posao> sviPoslovi = ClientController.getInstance().getAllPoslovi();
            ArrayList<PripadnostZadatkaPoslu> svePripadnosti = ClientController.getInstance().getAllPripadnostiZP();

            // Filter poslova koji sadrže izabrani zadatak
            ArrayList<Posao> posloviSaZadatkom = new ArrayList<>();
            for (PripadnostZadatkaPoslu p : svePripadnosti) {
                if (p.getZadatakID().equals(selektovaniZadatak.getZadatakID())) {
                    for (Posao posao : sviPoslovi) {
                        if (posao.getPosaoID().equals(p.getPosaoID())) {
                            posloviSaZadatkom.add(posao);
                            break;
                        }
                    }
                }
            }

            // Poslovi koji nemaju ovaj zadatak
            ArrayList<Posao> posloviBezZadatka = new ArrayList<>(sviPoslovi);
            for (Posao p : posloviSaZadatkom) {
                posloviBezZadatka.removeIf(pb -> pb.getPosaoID().equals(p.getPosaoID()));
            }

            // Postavljanje modela tabela
            TableModelPoslovi modelSaZadatkom = new TableModelPoslovi(posloviSaZadatkom);
            TableModelPoslovi modelBezZadatka = new TableModelPoslovi(posloviBezZadatka);
            jTablePosloviPovezani.setModel(modelSaZadatkom);
            jTablePosloviNepovezani.setModel(modelBezZadatka);

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri učitavanju poslova: " + ex.getMessage());
        }
    }
    
