    public void osveziSveSaBaze() {
        // === POSAO ===
        Posao selektovaniPosao = formPosao.getSelektovaniPosao();
        formPosao.popuniComboBoxPoslovi();
        boolean selektovaniPosaoJeUListi = false;
        ArrayList<Posao> poslovi = formPosao.getPoslovi();
        for (Posao p : poslovi) {
            if (p.equals(selektovaniPosao)) {
                selektovaniPosaoJeUListi = true;
                break;
            }
        }
        if (selektovaniPosaoJeUListi) {
            formPosao.setSelectedPosao(selektovaniPosao);
        } else {
            formPosao.setLastPosao();
        }

        // === ZAPOSLENI ===
        Zaposleni selektovaniZaposleni = formZaposleni.getSelektovaniZaposleni();
        formZaposleni.popuniComboBoxZaposleni();
        boolean selektovaniZaposleniJeUListi = false;
        ArrayList<Zaposleni> zaposleniList = formZaposleni.getZaposleni();
        for (Zaposleni z : zaposleniList) {
            if (z.equals(selektovaniZaposleni)) {
                selektovaniZaposleniJeUListi = true;
                break;
            }
        }
        if (selektovaniZaposleniJeUListi) {
            formZaposleni.setSelectedZaposleni(selektovaniZaposleni);
        } else {
            formZaposleni.setLastZaposleni();
        }

        // === ZADATAK ===
        Zadatak selektovaniZadatak = formZadatak.getSelektovaniZadatak();
        formZadatak.popuniComboBoxZadaci();
        boolean selektovaniZadatakJeUListi = false;
        ArrayList<Zadatak> zadaci = formZadatak.getZadaci();
        for (Zadatak z : zadaci) {
            if (z.equals(selektovaniZadatak)) {
                selektovaniZadatakJeUListi = true;
                break;
            }
        }
        if (selektovaniZadatakJeUListi) {
            formZadatak.setSelectedZadatak(selektovaniZadatak);
        } else {
            formZadatak.setLastZadatak();
        }
    }
