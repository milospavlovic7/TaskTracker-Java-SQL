    public void switchPanel(String panelName) {
        cardLayout.show(jPanelMain, panelName);
    }

    public void addNavigationItem(String panelName, Object selectedObject) {
        if (isNavigatingBack) return;
        navigationStack.push(new NavigationItem(panelName, selectedObject));
        System.out.println("Adding navigation item: Panel=" + panelName + ", Selected Object=" + selectedObject);
        jButtonNazad.setEnabled(true);
    }

    private void nazad() {
        if (navigationStack.isEmpty()) {
            jButtonNazad.setEnabled(false);
            return;
        }

        NavigationItem current = navigationStack.peek();
        System.out.println("New top of stack: Panel = " + current.getPanelName() + ", Selected Object = " + current.getSelectedObject());

        isNavigatingBack = true;
        switchPanel(current.getPanelName());

        switch (current.getPanelName()) {
            case "Zaposleni":
                if (current.getSelectedObject() instanceof Zaposleni) {
                    formZaposleni.setSelectedZaposleni((Zaposleni) current.getSelectedObject());
                }
                break;
            case "Posao":
                if (current.getSelectedObject() instanceof Posao) {
                    formPosao.setSelectedPosao((Posao) current.getSelectedObject());
                }
                break;
            case "Zadatak":
                if (current.getSelectedObject() instanceof Zadatak) {
                    formZadatak.setSelectedZadatak((Zadatak) current.getSelectedObject());
                }
                break;
        }

        isNavigatingBack = false;
        
        NavigationItem removed = navigationStack.pop();
        System.out.println("Removed navigation item: Panel = " + removed.getPanelName() + ", Selected Object = " + removed.getSelectedObject());

        if (navigationStack.isEmpty()) {
            jButtonNazad.setEnabled(false);
        }
    }

    public String getCurrentPanelName() {
        for (Component comp : jPanelMain.getComponents()) {
            if (comp.isVisible()) {
                return comp.getName();
            }
        }
        return null;
    }

    public void navigateToPanel(String newPanelName) {
        String currentPanelName = getCurrentPanelName();
        Object selectedObject = null;

        if (currentPanelName != null) {
            switch (currentPanelName) {
                case "Zaposleni":
                    selectedObject = formZaposleni.getSelektovaniZaposleni();
                    break;
                case "Posao":
                    selectedObject = formPosao.getSelektovaniPosao();
                    break;
                case "Zadatak":
                    selectedObject = formZadatak.getSelektovaniZadatak();
                    break;
            }

            addNavigationItem(currentPanelName, selectedObject);
        }

        switchPanel(newPanelName);
    }

